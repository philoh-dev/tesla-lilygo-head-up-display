def encode_rgb565a8(indicator: Indicator) -> bytes:
    with Image.open(indicator.source_directory / indicator.filename) as source:
        image = source.convert("RGBA")

    if image.size != (indicator.width, indicator.height):
        raise ValueError(
            f"{indicator.filename} is {image.width}x{image.height}; expected "
            f"{indicator.width}x{indicator.height}"
        )

    rgb565 = bytearray()
    alpha = bytearray()
    for red, green, blue, opacity in image.get_flattened_data():
        color = ((red >> 3) << 11) | ((green >> 2) << 5) | (blue >> 3)
        rgb565.extend(color.to_bytes(2, byteorder="little"))
        alpha.append(opacity)

    encoded = bytes(rgb565 + alpha)
    expected_size = indicator.width * indicator.height * 3
    if len(encoded) != expected_size:
        raise AssertionError(
            f"{indicator.filename} produced {len(encoded)} bytes; expected "
            f"{expected_size}"
        )
    return encoded


def format_bytes(data: bytes) -> str:
    lines = []
    for offset in range(0, len(data), 16):
        values = ", ".join(f"0x{value:02x}" for value in data[offset : offset + 16])
        lines.append(f"    {values},")
    return "\n".join(lines)


def generate_source(indicators: tuple[Indicator, ...], compressed: bool = False,
                    compact_park: bool = False) -> str:
    sections = [
        "// Generated by scripts/generate_indicator_images.py. Do not edit.",
        "",
        '#include "tesla_headup/adapters/lvgl_rm67162/indicator_images.hpp"',
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "namespace tesla_headup::platform::assets {",
        "namespace {",
        "",
        "constexpr lv_image_dsc_t make_descriptor(",
        "    const std::uint8_t* data,",
        "    std::size_t data_size,",
        "    std::uint16_t width,",
        "    std::uint16_t height) noexcept {",
        "    lv_image_dsc_t descriptor{};",
        "    descriptor.header.magic = LV_IMAGE_HEADER_MAGIC;",
        "    descriptor.header.cf = LV_COLOR_FORMAT_RGB565A8;",
        "    descriptor.header.flags = 0;",
        "    descriptor.header.w = width;",
        "    descriptor.header.h = height;",
        "    descriptor.header.stride = static_cast<std::uint16_t>(width * 2U);",
        "    descriptor.data_size = static_cast<std::uint32_t>(data_size);",
        "    descriptor.data = data;",
        "    return descriptor;",
        "}",
        "",
    ]

    descriptors = []
    storage = []
    if compressed or compact_park:
        sections.insert(4, '#include "tesla_headup/adapters/lvgl_rm67162/prepared_image_storage.hpp"')
    for indicator in indicators:
        data_name = f"{indicator.symbol}_data"
        encoded = encode_rgb565a8(indicator)
        unpacked_size = len(encoded)
        packed_image = compressed or (compact_park and indicator.symbol == "road_scene_park_image")
        if packed_image:
            encoded = compress_block(encoded)
        sections.extend(
            (
                f"alignas(4) constexpr std::uint8_t {data_name}[] = {{",
                format_bytes(encoded),
                "};",
                "",
            )
        )
        descriptors.extend(
            (
                f"{'lv_image_dsc_t' if packed_image else 'const lv_image_dsc_t'} {indicator.symbol} = make_descriptor(",
                "    nullptr," if packed_image else f"    {data_name},",
                f"    {unpacked_size}," if packed_image else f"    sizeof({data_name}),",
                f"    {indicator.width},",
                f"    {indicator.height});",
                "",
            )
        )
        if packed_image:
            storage.append(f"    {{&{indicator.symbol}, {data_name}, {unpacked_size}}},")

    sections.extend(("}  // namespace", ""))
    sections.extend(descriptors)
    if compressed or compact_park:
        variant = "wide" if compressed else "compact"
        sections.extend(("namespace {", "unsigned image_users = 0;",
                         "PreparedImageStorage stored_images[] = {", *storage, "};", "}",
                         f"bool retain_road_scene_{variant}_images() noexcept {{ return retain_images(stored_images, image_users); }}",
                         f"void release_road_scene_{variant}_images() noexcept {{ release_images(stored_images, image_users); }}"))
    sections.append("}  // namespace tesla_headup::platform::assets")
    sections.append("")
    return "\n".join(sections)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if the committed generated source is out of date",
    )
    arguments = parser.parse_args()
    generated_outputs = (
        (COMMON_OUTPUT_FILE, generate_source(INDICATORS)),
        (COMMON_OUTPUT_FILE.with_name("true_hud_indicator_images.cpp"),
         generate_source(TRUE_HUD_INDICATORS)),
        (
            ROAD_SCENE_OUTPUT_FILE,
            generate_source(ROAD_SCENE_INDICATORS, compact_park=True),
        ),
        (ROAD_SCENE_OUTPUT_FILE.with_name("road_scene_wide_images.cpp"),
         generate_source(WIDE_ROAD_SCENE_INDICATORS, compressed=True)),
    )

    if arguments.check:
        for output_file, generated in generated_outputs:
            if not output_file.exists() or output_file.read_text() != generated:
                print(f"Generated indicator images are stale: {output_file}")
                return 1
        return 0

    for output_file, generated in generated_outputs:
        output_file.parent.mkdir(parents=True, exist_ok=True)
        output_file.write_text(generated)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
